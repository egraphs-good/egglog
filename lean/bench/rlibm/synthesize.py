"""Generate the candidate Q40 coefficients using RLIBM-style rounding intervals.

Requires the HiGHS command-line LP solver. The separate Lean certificate
checks the selected integer coefficients against logarithm rounding cells.
"""
import argparse
from bisect import bisect_left
from decimal import Decimal, ROUND_HALF_EVEN, getcontext
from pathlib import Path
import subprocess
import tempfile

getcontext().prec = 85
D = Decimal
Q = 1 << 40
# Scale LP rows to keep HiGHS feasibility tolerances well below a bfloat ULP.
LP_SCALE = 1 << 20


def magnitude(bits):
    field, fraction = divmod(bits, 128)
    if field == 0:
        return D(fraction) * D(2) ** -133
    return D(128 + fraction) * D(2) ** (field - 134)


MAG = [magnitude(bits) for bits in range(0x7f80)]


def nearest(x):
    a = abs(x)
    hi = bisect_left(MAG, a)
    if hi == 0:
        return 0
    lo = hi - 1
    lower, upper = a - MAG[lo], MAG[hi] - a
    bits = lo if lower < upper or (lower == upper and lo % 2 == 0) else hi
    return bits | (0x8000 if x < 0 else 0)


def cell(bits):
    i = bits & 0x7fff
    if i == 0:
        return -MAG[1] / 2, MAG[1] / 2
    lo, hi = (MAG[i - 1] + MAG[i]) / 2, (MAG[i] + MAG[i + 1]) / 2
    return (-hi, -lo) if bits & 0x8000 else (lo, hi)


def split(bits):
    field, m = divmod(bits, 128)
    if field:
        return field - 127, m
    shift = 8 - m.bit_length()
    return -126 - shift, (m << shift) - 128


def constraints(base, k):
    ln_base = D(base).ln()
    log_two = D(2).ln() / ln_base
    significand = [(D(128 + m) / 128).ln() / ln_base for m in range(128)]
    lower, upper = [D('-Infinity')] * 128, [D('Infinity')] * 128
    expected = []
    for raw in range(1, 0x7f80):
        e, m = split(raw)
        bits = nearest(e * log_two + significand[m])
        expected.append(bits)
        lo, hi = cell(bits)
        offset = D(e * k) / Q
        lower[m] = max(lower[m], lo - offset)
        upper[m] = min(upper[m], hi - offset)
    return lower, upper, expected


def solve_segment(low, high, start, width, degree, solver, folder):
    # Maximize the distance to the nearest rounding boundary across the bucket.
    # Exact zero at x=1 fixes the constant of the first segment.
    lines = ['Maximize', ' obj: margin', 'Subject To']
    for t in range(width):
        m = start + t
        if m == 0:
            continue
        powers = ' + '.join(f'{t**j} c{j}' for j in range(degree + 1) if t != 0 or j == 0)
        lines.extend([f' lo{t}: {powers} - margin >= {low[m] * LP_SCALE:.16f}',
                      f' hi{t}: {powers} + margin <= {high[m] * LP_SCALE:.16f}'])
    lines.extend(['Bounds', ' c0 = 0' if start == 0 else ' c0 free',
                  *[f' c{j} free' for j in range(1, degree + 1)], ' margin >= 0', 'End'])
    model = folder / 'segment.lp'
    solution = folder / 'segment.sol'
    model.write_text('\n'.join(lines) + '\n')
    result = subprocess.run([solver, '--threads', '1', '--solver', 'simplex',
                             '--solution_file', str(solution), str(model)],
                            capture_output=True, text=True, check=True)
    src = solution.read_text()
    if 'Optimal' not in src:
        raise ValueError(f'LP for bucket {start} failed: {src}\n{result.stdout}')
    primal = src.split('# Columns', 1)[1].split('# Rows', 1)[0]
    values = dict(line.split() for line in primal.splitlines()[1:] if line.strip())
    return [int((D(values[f'c{j}']) * Q / LP_SCALE).to_integral_value(ROUND_HALF_EVEN))
            for j in range(degree + 1)]


def coefficients(base, width, degree, solver, directory):
    k = int((Q * D(2).ln() / D(base).ln()).to_integral_value(ROUND_HALF_EVEN))
    lo, hi, expected = constraints(base, k)
    rows = [solve_segment(lo, hi, start, width, degree, solver, directory) for start in range(0, 128, width)]
    for raw, bits in enumerate(expected, 1):
        e, m = split(raw)
        bucket, t = divmod(m, width)
        y = e * k + sum(c * t**i for i, c in enumerate(rows[bucket]))
        if nearest(D(y) / Q) != bits:
            raise ValueError(f'coefficient quantization changed log{base}(0x{raw:04x})')
    return k, rows


def render(cubic, quadratic):
    lines = ['import Egglog.Examples.Rlibm.Types', '',
             '/-! Generated by `bench/rlibm/synthesize.py` using HiGHS.',
             'The correctness proof checks these integer coefficients directly. -/',
             'namespace Rlibm', '',
             'structure Quadratic where', '  c0 : Int', '  c1 : Int', '  c2 : Int',
             '  deriving Inhabited', '', 'structure Cubic where', '  c0 : Int', '  c1 : Int',
             '  c2 : Int', '  c3 : Int', '  deriving Inhabited', '',
             'def exponentStep : LogBase → Int']
    for name, (k, _) in cubic:
        lines.append(f'  | .{name} => {k}')
    for fn, ty, datasets in [('coefficients', 'Cubic', cubic), ('quadratics', 'Quadratic', quadratic)]:
        lines += ['', f'def {fn} : LogBase → Array {ty}']
        for name, (_, rows) in datasets:
            lines += [f'  | .{name} => #[', ',\n'.join(
                '    ⟨' + ', '.join(map(str, row)) + '⟩' for row in rows) + ']']
    return '\n'.join(lines + ['', 'end Rlibm', ''])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--highs', default='highs')
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        bases = [('two', 2), ('ten', 10)]
        def fit(width, degree):
            return [(name, coefficients(base, width, degree, args.highs, Path(tmp)))
                    for name, base in bases]

        args.output.write_text(render(fit(16, 3), fit(8, 2)))


if __name__ == '__main__':
    main()
